import { Router } from "express";
import { z } from "zod";
import * as authController from "../controllers/adminAuth.controller.js";
import * as c from "../controllers/admin.controller.js";
import { adminSession, requireActiveAdmin } from "../middleware/admin.middleware.js";
import { adminLoginLimit } from "../middleware/rateLimit.middleware.js";
import { validate, objectIds } from "../middleware/validate.middleware.js";
const r = Router();
const loginSchema = z.object({ email: z.string().email().max(254), password: z.string().min(1).max(128), captchaToken: z.string().max(2048).optional() });
const codeSchema = z.object({ code: z.string().trim().min(6).max(32) });
const teacherSchema = z.object({ name: z.string().trim().min(1).max(120), email: z.string().email().max(254), username: z.string().trim().min(3).max(40).regex(/^[a-zA-Z0-9._-]+$/) });
r.post("/auth/start", authController.start);
r.get("/auth/entry-redirect", authController.entryRedirect);
r.post("/auth/login", adminLoginLimit, validate(loginSchema), authController.login);
r.use("/auth", adminSession);
r.get("/auth/setup", authController.setup);
r.post("/auth/verify", adminLoginLimit, validate(codeSchema), authController.verify);
r.get("/auth/me", authController.me);
r.post("/auth/logout", authController.logout);
r.use(adminSession, requireActiveAdmin);
r.get("/overview", c.overview);
r.get("/teachers", c.listTeachers);
r.post("/teachers", validate(teacherSchema), c.createTeacher);
r.put("/teachers/:id", objectIds, validate(teacherSchema.extend({ status: z.enum(["ACTIVE", "INACTIVE"]).optional() })), c.updateTeacher);
r.delete("/teachers/:id", objectIds, c.deleteTeacher);
r.post("/teachers/:id/reset-password", objectIds, c.resetTeacherPassword);
r.get("/students", c.listStudents);
r.put("/students/:id", objectIds, validate(z.object({ teacherId: z.string().optional(), name: z.string().max(120).optional(), email: z.string().email().optional().or(z.literal("")), course: z.string().max(120).optional(), section: z.string().max(120).optional(), status: z.enum(["ACTIVE", "INACTIVE"]).optional() })), c.updateStudent);
r.get("/sections", c.sections);
r.post("/sections/reassign", validate(z.object({ course: z.string().min(1), section: z.string().min(1), teacherId: z.string(), currentTeacherId: z.string().optional() })), c.reassignSection);
r.get("/assessments", c.assessments);
r.post("/assessments/:id/end", objectIds, c.endAssessment);
r.delete("/assessments/:id", objectIds, c.deleteAssessment);
r.get("/analytics", c.analytics);
r.get("/logs", c.logs);
r.get("/security", c.securitySettings);
r.post("/security/recovery-codes", authController.recoveryCodes);
r.post("/security/change-password", validate(z.object({ currentPassword: z.string().min(1).max(128), newPassword: z.string().min(12).max(72), confirmation: z.string().min(12).max(72) })), authController.changePassword);
r.post("/security/revoke-sessions", c.revokeSessions);
export default r;
