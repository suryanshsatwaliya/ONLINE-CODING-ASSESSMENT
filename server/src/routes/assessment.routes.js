import { Router } from "express";
import * as c from "../controllers/assessment.controller.js";
import { auth } from "../middleware/auth.middleware.js";
import { teacher } from "../middleware/teacher.middleware.js";
import { student } from "../middleware/student.middleware.js";
import { validate, objectIds } from "../middleware/validate.middleware.js";
import { assessmentSchema } from "../validators/assessment.validator.js";
const r = Router();
r.use(auth);
r.get("/", c.list);
r.get("/:id", objectIds, c.get);
r.use(teacher);
r.post("/", validate(assessmentSchema), c.create);
r.put("/:id", objectIds, validate(assessmentSchema), c.update);
r.post("/:id/assign", objectIds, c.assign);
r.get("/:id/assignments", objectIds, c.assignments);
r.post("/:id/access-code", objectIds, c.accessCode);
r.post("/:id/start", objectIds, c.start);
r.post("/:id/end", objectIds, c.end);
r.patch("/:id/publish", objectIds, c.publish);
r.get("/:id/monitor", objectIds, c.monitor);
r.get("/attempt/:id/events", objectIds, c.eventLog);
export default r;
